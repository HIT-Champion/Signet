-- Báo cáo động cho ứng dụng sinh (#589, phần nền của #587). Mỗi dòng sinh.bao_cao khai báo một báo cáo: bảng nguồn,
-- cột nhóm, phép tính, kiểu hiện. Trang báo cáo của /sinh đọc khai báo rồi gọi hàm gộp của PostgREST bằng token người
-- dùng, nên RLS vẫn lọc theo đơn vị; không view, không hàm (khung cấm trong sinh), không mã riêng cho báo cáo nào.
-- Tạo bằng vai trò moc_studio như Studio để khung (1792281604400_sinh_khung) gắn đơn vị, RLS, sổ kiểm toán: gac bỏ
-- qua superuser. COMMENT là nhãn: bảng hiện trên menu /sinh, khai báo bằng chính biểu mẫu chung.
set role moc_studio;
create type sinh.phep_tinh as enum ('đếm', 'tổng', 'trung bình');
create type sinh.kieu_hien as enum ('bảng', 'cột', 'tròn');
create table sinh.bao_cao (
  id bigint generated by default as identity primary key,
  ten text not null,
  bang text not null,
  nhom text not null,
  phep_tinh sinh.phep_tinh not null default 'đếm',
  cot_so text,
  kieu_hien sinh.kieu_hien not null default 'cột',
  constraint bao_cao_cot_so check (phep_tinh = 'đếm' or cot_so is not null)
);
comment on table sinh.bao_cao is 'Báo cáo';
comment on column sinh.bao_cao.ten is 'Tên báo cáo';
comment on column sinh.bao_cao.bang is 'Bảng nguồn';
comment on column sinh.bao_cao.nhom is 'Nhóm theo cột';
comment on column sinh.bao_cao.phep_tinh is 'Phép tính';
comment on column sinh.bao_cao.cot_so is 'Cột số (khi tính tổng, trung bình)';
comment on column sinh.bao_cao.kieu_hien is 'Kiểu hiện';
reset role;
select sinh_khung.kiem_tat_ca();

-- Hàm gộp (PGRST_DB_AGGREGATES_ENABLED) cho một báo cáo quét cả bảng: truy vấn của người dùng quá 5 giây thì dừng.
-- PostgREST áp setting của vai trò nó đổi sang. Setting của vai trò thuộc cả máy chủ, pg_dump không chép:
-- `moc backup restore` đặt lại bằng đúng đoạn này (SINH_ROLE_SETTINGS_SQL ở scripts/ung_dung.py, test so khớp)
alter role staff set statement_timeout = '5s';
alter role clerk set statement_timeout = '5s';
alter role manager set statement_timeout = '5s';
alter role director set statement_timeout = '5s';
alter role tenant_admin set statement_timeout = '5s';
