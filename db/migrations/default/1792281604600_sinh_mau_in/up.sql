-- Mẫu in cho ứng dụng sinh (#594, phần nền của #586). Mỗi dòng sinh.mau_in là một mẫu cho một bảng: văn bản thuần,
-- {{ten_cot}} là chỗ trống, dòng trống sang đoạn mới, dòng bắt đầu bằng "# " là tiêu đề. svc-files
-- (GET /api/sinh/{bang}/{id}/pdf?mau={id}) đọc mẫu và dòng bằng token người dùng, nên RLS vẫn lọc theo đơn vị.
-- Không lưu HTML: qua /rest/v1 sẽ vướng luật XSS của WAF, và mẫu không có thẻ thì không chạy script, không tải URL.
-- Tạo bằng vai trò moc_studio như Studio để khung (1792281604400_sinh_khung) gắn đơn vị, RLS, sổ kiểm toán: gac bỏ
-- qua superuser. COMMENT là nhãn: bảng hiện trên menu /sinh, mẫu nhập bằng chính biểu mẫu chung.
set role moc_studio;
create table sinh.mau_in (
  id bigint generated by default as identity primary key,
  ten text not null,
  bang text not null,
  noi_dung text not null,
  constraint mau_in_noi_dung check (char_length(noi_dung) <= 20000)
);
comment on table sinh.mau_in is 'Mẫu in';
comment on column sinh.mau_in.ten is 'Tên mẫu';
comment on column sinh.mau_in.bang is 'Bảng';
comment on column sinh.mau_in.noi_dung is 'Nội dung mẫu';
reset role;
select sinh_khung.kiem_tat_ca();
