def test_odd_table_name_gets_the_same_harness(world):
    name = f'sinh."Yêu cầu ""đặc biệt"" {uuid.uuid4().hex[:4]}"'
    studio(f"create table {name} (id bigint generated by default as identity primary key, ten text)")
    counts = (f"select (select count(*) from pg_policy where polrelid = '{name}'::regclass) || '/'"
              f" || (select count(*) from pg_trigger where tgrelid = '{name}'::regclass and not tgisinternal)")
    assert sql(counts) == [["2/3"]]
    sql(f"select sinh_khung.ap_khung('{name}'::regclass); select sinh_khung.ap_khung('{name}'::regclass)")
    assert sql(counts) == [["2/3"]]                                 # chạy lại không đổi gì
    assert as_user(world.staff_a1, f"insert into {name} (ten) values ('x') returning tenant_id") == world.tenant_a


