def psql(role: str, script: str, one: bool = True) -> str:
    """Chạy `script` bằng vai trò `role` (trong một giao dịch nếu `one`); trả dòng cuối của kết quả."""
    sql(f"alter role {role} login")
    try:
        proc = subprocess.run(["docker", "exec", "-i", PG, "psql", "-X", "-q", "-A", "-t", "-v", "ON_ERROR_STOP=1",
                               *(["-1"] if one else []), "-U", role, "-d", "moc", "-f", "-"],
                              input=script, capture_output=True, text=True, timeout=60)
    finally:
        sql(f"alter role {role} nologin")
    if proc.returncode != 0:
        raise SQLError(proc.stderr.strip())
    lines = proc.stdout.strip().splitlines()
    return lines[-1] if lines else ""


def studio(statement: str) -> str:
    return psql("moc_studio", statement)


def as_user(user: User, statement: str) -> str:
    """Như PostgREST nhận token của `user`: đặt claim, gọi hàm trước yêu cầu, đổi sang vai trò của người đó."""
    claims = json.dumps({"sub": user.sub, CLAIMS: {"x-hasura-default-role": user.role,
                                                  "x-hasura-tenant-id": user.tenant, "x-hasura-user-id": user.sub}})
    return psql("authenticator", f"\\o /dev/null\nselect set_config('request.jwt.claims', '{claims}', true);\n"
                                 f"select sinh_khung.truoc_yeu_cau();\nset local role {user.role};\n\\o\n{statement}")


