def test_restore_and_migration_create_the_same_roles():
    """`moc backup restore` tạo lại vai trò bằng SINH_ROLES_SQL: phải đúng đoạn của migration, chạy lại được."""
    assert ung_dung.SINH_ROLES_SQL in MIGRATION.read_text(encoding="utf-8")
    sql(ung_dung.SINH_ROLES_SQL)
    members = sql("select string_agg(r.rolname, ',' order by r.rolname) from pg_auth_members m"
                  " join pg_roles r on r.oid = m.roleid join pg_roles u on u.oid = m.member"
                  " where u.rolname = 'authenticator'")
    assert members == [[",".join(sorted(ung_dung.USER_ROLES))]]      # không có moc_studio
    assert sql("select rolinherit, rolsuper, rolbypassrls from pg_roles where rolname = 'authenticator'") \
        == [["f", "f", "f"]]
    assert sql("select rolname from pg_roles where rolname in ('authenticator', 'moc_studio', 'moc_harness')"
               " and (rolsuper or rolbypassrls)") == []
    # chỉ hai hàm SECURITY DEFINER, chủ là moc_harness (không superuser)
    assert sql("select proname || ':' || proowner::regrole from pg_proc"
               " where pronamespace = 'sinh_khung'::regnamespace and prosecdef order by 1") \
        == [["ap_khung:moc_harness"], ["ghi_ddl:moc_harness"]]


def test_new_table_gets_the_harness(bang):
    oid = f"'{bang}'::regclass"
    assert sql(f"select string_agg(attname, ',' order by attname) from pg_attribute where attrelid = {oid}"
               " and attname in ('tenant_id', 'created_by', 'created_at') and not attisdropped") \
        == [["created_at,created_by,tenant_id"]]
    # Không FORCE: chủ bảng moc_studio là người vận hành, vượt RLS (trình sửa bảng của Studio dùng được)
    assert sql(f"select relrowsecurity, relforcerowsecurity, relowner::regrole from pg_class where oid = {oid}") \
        == [["t", "f", "moc_studio"]]
    assert sql(f"select string_agg(polname || ':' || polpermissive || ':' || polroles::text, ',' order by polname)"
               f" from pg_policy where polrelid = {oid}") == [["moc_don_vi:false:{0},moc_mo:true:{0}"]]
    assert sql(f"select string_agg(tgname, ',' order by tgname) from pg_trigger where tgrelid = {oid}"
               " and not tgisinternal") == [["moc_cot_chuan,moc_khong_xoa_het,moc_so"]]
    sql("select sinh_khung.kiem_tat_ca()")


def test_tenants_only_see_their_own_rows(world, bang):
    a, b = world.tenant_a, world.tenant_b
    # Gửi tenant_id, created_by của người khác: máy chủ thay bằng giá trị từ token
    assert as_user(world.staff_a1, f"insert into {bang} (tieu_de, tenant_id, created_by)"
                                   f" values ('của A', '{b}', 'gia') returning tenant_id || '|' || created_by") \
        == f"{a}|{world.staff_a1.sub}"
    as_user(world.clerk_b, f"insert into {bang} (tieu_de) values ('của B')")
    count = f"select count(*) filter (where tenant_id = '{a}') || '/' || count(*) filter (where tenant_id = '{b}')" \
            f" from {bang}"
    assert as_user(world.staff_a1, count) == "1/0"
    assert as_user(world.admin_a, count) == "1/0"                   # tenant_admin cũng chỉ trong đơn vị
    assert as_user(world.clerk_b, count) == "0/1"
    assert as_user(world.clerk_b, f"with u as (update {bang} set tieu_de = 'B sửa' where tenant_id = '{a}'"
                                  " returning 1) select count(*) from u") == "0"
    assert studio(count) == "1/1"                                   # chủ bảng thấy mọi đơn vị


