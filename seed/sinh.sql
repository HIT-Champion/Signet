-- Bảng mẫu của ứng dụng sinh từ Studio (#566): "Quản lý yêu cầu" hiện trên /sinh. Tạo bằng vai trò moc_studio như
-- Studio, để khung (migration 1792281604400_sinh_khung) gắn cột chuẩn, RLS, sổ; chủ bảng không có claim nên dòng
-- mẫu ghi tenant_id rõ. COMMENT là nhãn trên giao diện. Chạy lại nhiều lần được. KHÔNG dùng trên hệ thống thật.
begin;
set local moc.actor = 'seed';
set local role moc_studio;

do $$ begin
  if to_regtype('sinh.trang_thai') is null then
    create type sinh.trang_thai as enum ('mới', 'đang xử lý', 'xong');      -- enum PG → ô chọn trên biểu mẫu
  end if;
end $$;

create table if not exists sinh.yeu_cau (
  id bigint generated by default as identity primary key,
  tieu_de text not null,
  noi_dung text,
  han date,
  trang_thai sinh.trang_thai not null default 'mới'
);
comment on table sinh.yeu_cau is 'Quản lý yêu cầu';
comment on column sinh.yeu_cau.tieu_de is 'Tiêu đề';
comment on column sinh.yeu_cau.noi_dung is 'Nội dung';
comment on column sinh.yeu_cau.han is 'Hạn xử lý';
comment on column sinh.yeu_cau.trang_thai is 'Trạng thái';

insert into sinh.yeu_cau (tenant_id, created_by, tieu_de, noi_dung, han, trang_thai)
select t, 'seed', v.tieu_de, v.noi_dung, current_date + v.ngay, v.trang_thai::sinh.trang_thai
  from (values ('c300d5bb-028f-44cc-ba10-7b5277a4225d'::uuid), ('318da474-60d6-4a90-aa7f-928b31b8fc59'::uuid)) d (t),
       (values ('Cấp lại thẻ sinh viên', 'Thẻ bị mất, cần cấp lại trước kỳ thi', 7, 'mới'),
               ('Sửa máy chiếu phòng A1-301', 'Máy chiếu không nhận tín hiệu HDMI', 2, 'đang xử lý'),
               ('Xác nhận lịch bảo vệ đồ án', null, -3, 'xong')) v (tieu_de, noi_dung, ngay, trang_thai)
 where not exists (select 1 from sinh.yeu_cau);

-- Mẫu in mẫu (#594): bảng sinh.mau_in do migration 1792281604600 tạo; nút In của bảng yeu_cau trên /sinh dùng nó.
-- Văn bản thuần: {{ten_cot}} là chỗ trống, dòng trống sang đoạn mới, dòng "# " là tiêu đề
insert into sinh.mau_in (tenant_id, created_by, ten, bang, noi_dung)
select t, 'seed', 'Phiếu yêu cầu', 'yeu_cau', '# Phiếu yêu cầu

Tiêu đề: {{tieu_de}}
Hạn xử lý: {{han}}
Trạng thái: {{trang_thai}}

Nội dung: {{noi_dung}}'
  from (values ('c300d5bb-028f-44cc-ba10-7b5277a4225d'::uuid), ('318da474-60d6-4a90-aa7f-928b31b8fc59'::uuid)) d (t)
 where not exists (select 1 from sinh.mau_in);

reset role;
select sinh_khung.kiem_tat_ca();          -- bảng nào trong sinh thiếu khung thì hủy cả lần nạp
commit;
